// Turns a schedule CSV into SQL that inserts its flights, teams and races.
//
// Usage: node scripts/import-schedule.ts schedule/<competition>/config.json > out.sql
//        supabase db query --linked -f out.sql
//
// The CSV's first column is the race number, and each flight occupies two
// columns (left half, right half). A row only fills in one flight's columns.
//
// Re-running is safe: flights are matched by id, teams by name, and races by
// (competition, league, number).
import * as fs from "node:fs";
import * as path from "node:path";

type FlightConfig = {
  // Fixed so re-runs don't duplicate the flight. Also names the flight photos:
  // public/halfflights/<id>_left.jpeg and <id>_right.jpeg.
  id: string;
  // CSV headers of this flight's left and right halves.
  columns: [string, string];
  // Omit these to reuse an existing flight row with this id.
  name?: string;
  lname?: string;
  lnumbers?: number[];
  rname?: string;
  rnumbers?: number[];
};

type Config = {
  competition: string;
  league: string;
  // Path to the CSV, relative to the config file.
  schedule: string;
  flights: FlightConfig[];
  // Maps names in the CSV to team names in the database. Unmapped names are
  // used as-is.
  teams?: Record<string, string>;
};

const configPath = process.argv[2];
if (!configPath) {
  console.error("Usage: node scripts/import-schedule.ts <config.json>");
  process.exit(1);
}
const config: Config = JSON.parse(fs.readFileSync(configPath, "utf-8"));
const csv = fs.readFileSync(
  path.join(path.dirname(configPath), config.schedule),
  "utf-8",
);

const [header, ...rows] = csv
  .trim()
  .split(/\r?\n/)
  .map((line) => line.split(",").map((cell) => cell.trim()));

const column = (name: string): number => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`No column "${name}" in ${config.schedule}`);
  return i;
};

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const team = (csvName: string) => config.teams?.[csvName] ?? csvName;

const races: { number: number; flight: string; lteam: string; rteam: string }[] =
  [];
for (const row of rows) {
  const number = parseInt(row[0], 10);
  if (isNaN(number)) continue;
  for (const flight of config.flights) {
    const l = row[column(flight.columns[0])];
    const r = row[column(flight.columns[1])];
    if (l && r) {
      races.push({ number, flight: flight.id, lteam: team(l), rteam: team(r) });
    } else if (l || r) {
      throw new Error(`Race ${number} has only one team in ${flight.id}`);
    }
  }
}

const numbers = races.map((r) => r.number);
if (new Set(numbers).size !== numbers.length) {
  throw new Error("A race number appears more than once");
}

const sql: string[] = [
  `-- Generated by scripts/import-schedule.ts from ${configPath}`,
  "BEGIN;",
  "",
];

const newFlights = config.flights.filter((f) => f.name !== undefined);
if (newFlights.length > 0) {
  sql.push(
    "INSERT INTO flight (id, name, lname, lnumbers, rname, rnumbers) VALUES",
    newFlights
      .map(
        (f) =>
          `  (${q(f.id)}, ${q(f.name!)}, ${q(f.lname!)}, ARRAY[${f.lnumbers!.join(", ")}], ${q(f.rname!)}, ARRAY[${f.rnumbers!.join(", ")}])`,
      )
      .join(",\n"),
    "ON CONFLICT (id) DO NOTHING;",
    "",
  );
}

const teams = [...new Set(races.flatMap((r) => [r.lteam, r.rteam]))].sort();
sql.push(
  "INSERT INTO team (name) VALUES",
  teams.map((t) => `  (${q(t)})`).join(",\n"),
  "ON CONFLICT (name) DO NOTHING;",
  "",
  "INSERT INTO race (number, competition, league, flight, lteam, rteam)",
  `SELECT v.number, ${q(config.competition)}, ${q(config.league)}, v.flight::uuid, lt.id, rt.id`,
  "FROM (VALUES",
  races
    .map(
      (r) => `  (${r.number}, ${q(r.flight)}, ${q(r.lteam)}, ${q(r.rteam)})`,
    )
    .join(",\n"),
  ") AS v(number, flight, lteam, rteam)",
  "JOIN team lt ON lt.name = v.lteam",
  "JOIN team rt ON rt.name = v.rteam",
  "WHERE NOT EXISTS (",
  "  SELECT 1 FROM race",
  `  WHERE competition = ${q(config.competition)} AND league = ${q(config.league)} AND number = v.number`,
  ");",
  "",
  "COMMIT;",
);

console.log(sql.join("\n"));
